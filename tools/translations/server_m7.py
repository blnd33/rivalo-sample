def merge(name, entries):
    path = LANG / name
    data = json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=collections.OrderedDict)
    added = 0
    for k, v in entries.items():
        if k not in data:
            data[k] = v
            added += 1
    path.write_text(json.dumps(data, ensure_ascii=False, indent=4) + '\n', encoding='utf-8', newline='\n')
    print(name, 'added', added, 'total', len(data))


